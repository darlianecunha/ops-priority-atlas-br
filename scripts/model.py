def emis(seg,dwt,t_anch,t_berth,fuel='HFO'):
    p=params(seg,dwt); sme,sae,sbo=SFOC[fuel]; ef=EF[fuel]
    anch=(p['aa']*t_anch*sae + p['ba']*t_anch*sbo)/1e6*ef
